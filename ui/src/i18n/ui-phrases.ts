type PhraseLocale = "zh-CN";

const phrasesByLocale: Record<PhraseLocale, Readonly<Record<string, string>>> = {
  "zh-CN": zhCNUiPhrases,
};

function translateDuration(value: string): string {
  return value
    .replace(/\bseconds?\b/g, "秒")
    .replace(/\bminutes?\b/g, "分钟")
    .replace(/\bhours?\b/g, "小时")
    .replace(/\bdays?\b/g, "天")
    .replace(/\bweeks?\b/g, "周")
    .replace(/\bmonths?\b/g, "个月");
}

function translateDynamicZhCNPhrase(value: string): string | null {
  const durationOnly = value.match(/^(\d+(?:\.\d+)?\s*(?:seconds?|minutes?|hours?|days?|weeks?|months?))$/);
  const durationOnlyValue = durationOnly?.[1];
  if (durationOnlyValue) return translateDuration(durationOnlyValue);

  const plannedTasks = value.match(/^(\d+) tasks planned$/);
  const plannedTasksCount = plannedTasks?.[1];
  if (plannedTasksCount) return `${plannedTasksCount} 个任务已计划`;

  const projectCount = value.match(/^(\d+) projects?$/);
  const projectCountValue = projectCount?.[1];
  if (projectCountValue) return `${projectCountValue} 个项目`;

  const finishedAgo = value.match(/^Finished (.+) ago$/);
  const finishedAgoValue = finishedAgo?.[1];
  if (finishedAgoValue) return `${translateDuration(finishedAgoValue)} 前完成`;

  const timeAgo = value.match(/^(\d+(?:\.\d+)?\s*(?:h|m|s|d|seconds?|minutes?|hours?|days?|weeks?|months?)) ago$/);
  const timeAgoValue = timeAgo?.[1];
  if (timeAgoValue) return `${translateDuration(timeAgoValue)} 前`;

  const workedFor = value.match(/^worked for (.+)$/);
  const workedForValue = workedFor?.[1];
  if (workedForValue) return `工作了 ${translateDuration(workedForValue)}`;

  const failedAfter = value.match(/^failed after (.+)$/);
  const failedAfterValue = failedAfter?.[1];
  if (failedAfterValue) return `${translateDuration(failedAfterValue)}后失败`;

  const runSucceeded = value.match(/^(.+) run ([a-z0-9]+) succeeded$/i);
  const runSucceededActor = runSucceeded?.[1];
  const runSucceededId = runSucceeded?.[2];
  if (runSucceededActor && runSucceededId) return `${runSucceededActor} 运行 ${runSucceededId} 成功`;

  const approvalCreated = value.match(/^Approval request created (.+) ago$/);
  const approvalCreatedValue = approvalCreated?.[1];
  if (approvalCreatedValue) return `审批请求创建于 ${translateDuration(approvalCreatedValue)} 前`;

  return null;
}

export function translateUiPhrase(value: string, locale: string): string | null {
  if (locale !== "zh-CN") return null;
  return phrasesByLocale[locale][value] ?? translateDynamicZhCNPhrase(value);
}
